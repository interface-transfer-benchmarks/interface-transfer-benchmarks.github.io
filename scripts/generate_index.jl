include(joinpath(@__DIR__, "cases.jl"))

const COVERAGE_HEADING = "## Current benchmark coverage"

function write_index(cases, path::AbstractString)
    open(path, "w") do io
        println(io, "# Benchmark index")
        println(io)
        println(io, "| ID | Benchmark | Class | Status | Reference |")
        println(io, "|---|---|---|---|---|")
        for case in cases
            println(
                io,
                "| ", table_cell(case.id),
                " | [", table_cell(case.title), "](cases/", case.filename, ")",
                " | ", table_cell(getmeta(case.metadata, "benchmark_class", "")),
                " | ", table_cell(getmeta(case.metadata, "status", "")),
                " | ", table_cell(getmeta(case.metadata, "reference_type", "")),
                " |",
            )
        end
        println(io)
        println(io, "Reference data is under `data/<ID>/`, reference plots under `figures/`.")
        println(io)
        println(io, "Generated by `scripts/generate_index.jl`.")
    end
end

function write_coverage(cases, path::AbstractString)
    text = read(path, String)
    marker = findfirst(COVERAGE_HEADING, text)
    marker === nothing && error("$path has no `$COVERAGE_HEADING` section.")

    open(path, "w") do io
        print(io, text[1:first(marker)-1])
        println(io, COVERAGE_HEADING)
        println(io)
        println(io, "| ID | Process | Geometry | Reference type | Primary numerical challenge |")
        println(io, "|---|---|---|---|---|")
        for case in cases
            metadata = case.metadata
            geometry = strip(string(
                table_cell(getmeta(metadata, "dimension", "")), " ",
                table_cell(getmeta(metadata, "geometry", "")),
            ))
            println(
                io,
                "| ", table_cell(case.id),
                " | ", table_cell(getmeta(metadata, "process", "")),
                " | ", geometry,
                " | ", table_cell(getmeta(metadata, "reference_type", "")),
                " | ", table_cell(getmeta(metadata, "numerical_challenge", "")),
                " |",
            )
        end
        println(io)
        println(io, "Generated by `scripts/generate_index.jl`.")
    end
end

function generate_index(root::AbstractString = REPO_ROOT)
    cases = load_cases(root)
    write_index(cases, joinpath(root, "index.md"))
    write_coverage(cases, joinpath(root, "taxonomy.md"))
    return cases
end

if abspath(PROGRAM_FILE) == @__FILE__
    generate_index()
end
