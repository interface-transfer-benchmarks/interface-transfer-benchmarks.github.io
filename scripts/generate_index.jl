include(joinpath(@__DIR__, "cases.jl"))

function write_index(cases, path::AbstractString)
    open(path, "w") do io
        println(io, "# Benchmark index")
        println(io)
        println(io, "| ID | Benchmark | Process | Motion | Interface | Domains | Domain | Equations | Reference | Status |")
        println(io, "|---|---|---|---|---|---|---|---|---|---|")
        for case in cases
            println(
                io,
                "| ", table_cell(case.id),
                " | [", table_cell(case.title), "](cases/", case.filename, ")",
                " | ", table_cell(getmeta(case.metadata, "process", "")),
                " | ", table_cell(getmeta(case.metadata, "interface_motion", "")),
                " | ", table_cell(getmeta(case.metadata, "interface_condition", "")),
                " | ", domains_cell(case.metadata),
                " | ", geometry_cell(case.metadata),
                " | ", table_cell(getmeta(case.metadata, "equations", "")),
                " | ", table_cell(getmeta(case.metadata, "reference", "")),
                " | ", table_cell(getmeta(case.metadata, "status", "")),
                " |",
            )
        end
        println(io)
        println(io, "Reference data is under `data/<ID>/`, submitted results under `results/<solver>/`.")
        println(io)
        println(io, "Figures are not stored; they are drawn from that data when the site is built.")
        println(io)
        println(io, "Generated by `scripts/generate_index.jl`.")
    end
end

function generate_index(root::AbstractString = REPO_ROOT)
    cases = load_cases(root)
    write_index(cases, joinpath(root, "index.md"))
    return cases
end

if abspath(PROGRAM_FILE) == @__FILE__
    generate_index()
end
